#!/usr/bin/env python3
"""Writes godot/src/render/globe_lite.gdshader from globe.gdshader: the same map without the high tier's close-zoom smoothing (smooth_id / hq_id), rim light and Bezel strokes.
Tiers 0 and 1 (and every camera move on a slow machine) run this one: a quarter of the code to compile (the ANGLE / Direct3D shader compile is what makes a first start slow on
old Intel graphics) and far fewer registers and texture reads per pixel. Run after editing globe.gdshader:  python3 tools/make_lite_shader.py [--check]"""
import sys, re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent / "godot/src/render"
src = (root / "globe.gdshader").read_text().split("\n")

def find(prefix, start=0):
    for i in range(start, len(src)):
        if src[i].startswith(prefix): return i
    raise SystemExit("anchor not found: " + prefix)

lines = list(src)
def cut(a, b, repl=None):  # replace lines[a:b) (indices into the ORIGINAL list, processed from the bottom up)
    lines[a:b] = repl or []

# bottom-up so earlier indices stay valid
i_chain = find("\t\tif (quality >= 2 && atlas == 1) {")
i_else = i_chain
while not src[i_else].startswith("\t\t} else {"): i_else += 1
# the else that follows `else if (quality >= 2) {`: the first "\t\t} else {" after that branch
i_q2b = find("\t\t} else if (quality >= 2) {", i_chain)
i_else = i_q2b
while not src[i_else].startswith("\t\t} else {"): i_else += 1
cut(i_chain, i_else + 1, ["\t\t{"])
i_rim = find("\t\tif (quality >= 2 && id != 0 && hc == 0 && atlas == 0) {")
i_rim_end = find("\t\t// ---- relation patterns", i_rim)
cut(i_rim, i_rim_end)
i_hq = find("\t\tbool hq = quality >= 2 && tpp < 0.5;")
cut(i_hq, i_hq + 2, ["\t\tbool hq = false;", "\t\tint id = id_at(ti);"])
i_sid = find("int sid(vec2 tt, bool hqf) {")
cut(i_sid, i_sid + 5, ["int sid(vec2 tt, bool hqf) {", "\treturn id_at(ivec2(floor(tt)));", "}"])
i_a = find("// Bilinear-threshold smoothed province id")
i_b = find("int owner_of(int id) {")
cut(i_a, i_b)
head = ["// GENERATED by tools/make_lite_shader.py from globe.gdshader: tiers 0 and 1 (nearest-texel ids, no close-zoom smoothing, rim light or Bezel strokes). Do not edit."]
out = "\n".join(head + lines)
for bad in ("smooth_id", "hq_id", "vnoise", "hash21"):
    assert bad not in out, bad
dst = root / "globe_lite.gdshader"
if "--check" in sys.argv:
    sys.exit(0 if dst.exists() and dst.read_text() == out else 1)
dst.write_text(out)
print("wrote", dst, len(out.split("\n")), "lines (full:", len(src), ")")
